"""Offline tests for AgentLoop staged generation. No DeepSeek API calls."""
import json
from types import SimpleNamespace
from unittest.mock import Mock

import pytest

from agent.agent_loop import AgentLoop

FILES = [
    "game_logic.py", "main.py", "tests/test_game_logic.py",
    "tests/test_main.py", "README.md", "requirements.txt",
]


def response_for(filename, content="# generated by fake client\n"):
    call = SimpleNamespace(
        id="fake", function=SimpleNamespace(
            name="write_file", arguments=json.dumps({
                "file_path": filename, "content": content,
            }),
        ),
    )
    return SimpleNamespace(
        usage=SimpleNamespace(prompt_tokens=100, completion_tokens=50),
        choices=[SimpleNamespace(
            finish_reason="tool_calls",
            message=SimpleNamespace(tool_calls=[call], content=None),
        )],
    )


def make_agent(tmp_path, responses, **kwargs):
    client = Mock()
    client.chat.side_effect = responses
    agent = AgentLoop(
        deepseek_client=client,
        project_directory=tmp_path,
        staged_generation=True,
        **kwargs,
    )
    return agent, client


def fake_pytest(monkeypatch, *return_codes):
    results = iter(return_codes)
    calls = []

    def run(cmd, **kwargs):
        calls.append((cmd, kwargs))
        return SimpleNamespace(
            returncode=next(results),
            stdout="tests/test_main.py failed" if len(calls) == 1 and return_codes[0] else "6 passed",
            stderr="",
        )

    monkeypatch.setattr("agent.agent_loop.subprocess.run", run)
    return calls


def test_staged_generates_all_six_files(tmp_path, monkeypatch):
    def forbidden(*args, **kwargs):
        pytest.fail("Generated tests must not run on the host")
    monkeypatch.setattr("agent.agent_loop.subprocess.run", forbidden)
    agent, client = make_agent(tmp_path, [response_for(f) for f in FILES])
    result = agent.run({"project_name": "Space Fractions"})
    assert result["status"] == "validation_skipped"
    assert result["iterations"] == 6
    assert client.chat.call_count == 6
    assert all((tmp_path / f).is_file() for f in FILES)
    for call in client.chat.call_args_list:
        assert "tool_choice" not in call.kwargs


