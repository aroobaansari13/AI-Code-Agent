def test_staged_reports_syntax_error(tmp_path, monkeypatch):
    def forbidden(*args, **kwargs):
        pytest.fail("Generated tests must not run on the host")
    monkeypatch.setattr("agent.agent_loop.subprocess.run", forbidden)
    responses = [response_for(f, "def broken(:\n" if f == "game_logic.py" else "# valid\n") for f in FILES]
    agent, client = make_agent(tmp_path, responses)
    result = agent.run({"project_name": "Space Fractions"})
    assert result["status"] == "validation_failed"
    assert "game_logic.py" in result["message"]
    assert client.chat.call_count == 6


def test_staged_stops_before_sixth_request(tmp_path, monkeypatch):
    def forbidden(*args, **kwargs):
        pytest.fail("Validation should not run for incomplete generation")
    monkeypatch.setattr("agent.agent_loop.subprocess.run", forbidden)
    agent, client = make_agent(
        tmp_path, [response_for(f) for f in FILES[:5]], max_iterations=5,
    )
    result = agent.run({"project_name": "Space Fractions"})
    assert result["status"] == "iteration_limit"
    assert client.chat.call_count == 5
    assert not (tmp_path / "requirements.txt").exists()


def test_staged_rejects_wrong_file_path(tmp_path, monkeypatch):
    agent, client = make_agent(tmp_path, [response_for("wrong.py")])
    result = agent.run({"project_name": "Space Fractions"})
    assert result["status"] == "tool_error"
    assert client.chat.call_count == 1
    assert not (tmp_path / "wrong.py").exists()
